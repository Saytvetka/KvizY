"""Тексты всех запросов к ИИ. Общие правила (язык, «не выдумывай», «только JSON») — SYSTEM_RULES в app/ai/__init__.py.

Здесь только то, ЧТО попросить. Проверка ответа, нумерация, подписи тем, хранение — код (app/work/pipeline.py).
"""
from __future__ import annotations

from app import config

TOPIC_RULES = (
    "ТЕМЫ: определи, сколько тем в материале. Если тема одна — у всех элементов одна и та же тема. "
    "Если файлов несколько и каждый про своё — тема = о чём файл (коротко, 2–6 слов; можно опираться на имя файла "
    "из метки [Файл N: имя]). Если в одном файле несколько крупных тем — раздели. Названия тем короткие и понятные."
)


def _note(note: str) -> str:
    return f"\n\nУТОЧНЕНИЕ ОТ СТУДЕНТА (выполни, если не противоречит правилам): {note.strip()}" if note.strip() else ""


def _part(part: tuple[int, int]) -> str:
    i, n = part
    return f"\n\nЭто часть {i} из {n} большого материала: работай только с этой частью." if n > 1 else ""


def tickets(material: str, note: str = "", part: tuple[int, int] = (1, 1), only_topics: list[str] | None = None) -> str:
    focus = ""
    if only_topics:
        focus = ("\n\nВ прошлый раз эти темы остались без вопросов. Составь билеты ТОЛЬКО по ним: "
                 + "; ".join(only_topics))
    return f"""Составь ВСЕ возможные экзаменационные билеты по материалу.

1. {TOPIC_RULES}
2. Билеты должны покрыть ВСЕ темы и все важные части материала: ни одна тема и ни один крупный раздел не должны остаться без вопросов.
3. В каждом билете {config.TICKET_QUESTIONS} вопроса (можно 2, если материала мало). Вопросы в одном билете — про разные стороны темы
   или из разных тем; не повторяй вопросы между билетами.
4. Вопросы — как на настоящем экзамене: «Объясните…», «Сравните…», «Перечислите и охарактеризуйте…», «Какова роль…»,
   «Приведите пример…». Каждый вопрос понятен без материала перед глазами.
5. У каждого вопроса укажи тему (topic) — одно из названий из списка topics.
6. Сколько билетов — реши сам по объёму материала (обычно 5–30), чтобы покрыть всё.{focus}

Верни JSON:
{{"topics": ["тема 1", "тема 2"],
  "tickets": [{{"questions": [{{"text": "вопрос", "topic": "тема 1"}}, {{"text": "вопрос", "topic": "тема 2"}}]}}]}}{_part(part)}{_note(note)}

МАТЕРИАЛ:
{material}"""


def summary(material: str, note: str = "", part: tuple[int, int] = (1, 1)) -> str:
    return f"""Сделай структурированный конспект материала для подготовки к экзамену.

1. {TOPIC_RULES}
2. Конспект разбит на разделы в порядке материала. У каждого раздела: тема (topic, из списка topics), заголовок,
   главное — короткими пунктами (3–10 пунктов, каждый — законченная мысль: факт, определение, причина, вывод, дата, формула),
   и термины раздела с определениями (если есть).
3. Пиши сжато, но так, чтобы по конспекту можно было ответить на экзамене. Ничего важного не пропускай.
   Самое важное слово в пункте можно выделить **жирным**.
4. Не добавляй того, чего нет в материале.

Верни JSON:
{{"topics": ["тема 1"],
  "sections": [{{"topic": "тема 1", "title": "заголовок раздела",
                "points": ["пункт", "пункт"],
                "terms": [{{"term": "термин", "definition": "определение"}}]}}]}}{_part(part)}{_note(note)}

МАТЕРИАЛ:
{material}"""


def answer(material: str, question: str, partial: bool = False) -> str:
    where = ("Ниже — самые подходящие к вопросу части материала (весь материал не поместился)."
             if partial else "Ниже — весь материал.")
    return f"""Ответь на вопрос студента, используя ТОЛЬКО материал ниже. {where}

ВОПРОС: {question.strip()}

Правила:
1. Отвечай только тем, что есть в материале. Свои знания не добавляй.
2. Если в материале ответа нет — found = false, а в answer честно напиши, что в файлах этого нет
   (можно одной фразой сказать, что в материале есть близкого по теме).
3. Если ответ есть частично — found = true, ответь тем, что есть, и прямо скажи, чего в материале не хватает.
4. Ответ — понятный, по пунктам, если так яснее. Самое важное можно выделить **жирным**.
5. quotes — 1–3 ДОСЛОВНЫЕ цитаты из материала, на которых держится ответ.
6. topic — о какой теме материала вопрос (коротко), source — из какого файла (имя из метки [Файл N: имя]), если понятно.

Верни JSON:
{{"found": true, "answer": "ответ", "quotes": ["дословная цитата"], "topic": "тема", "source": "имя файла"}}

МАТЕРИАЛ:
{material}"""


TYPE_TEXT = {
    "single": "single — один верный ответ из 4 вариантов (correct — номер верного, с 0)",
    "multi": "multi — несколько верных из 4–5 вариантов (correct — список номеров верных, с 0; верных 2 или больше, но не все)",
    "tf": "tf — утверждение «верно/неверно» (options: [\"Верно\", \"Неверно\"], correct — 0 если верно, 1 если неверно)",
}


def questions(material: str, counts: dict[str, int], level: dict, note: str = "", part: tuple[int, int] = (1, 1),
              avoid: list[str] | None = None) -> str:
    total = sum(counts.values())
    plan = "\n".join(f"   - {TYPE_TEXT[t]}: {k} шт." for t, k in counts.items() if k)
    avoid_text = ""
    if avoid:
        avoid_text = "\n\nЭти вопросы уже есть — НЕ повторяй их и не задавай похожие:\n" + "\n".join(f"- {a}" for a in avoid[:60])
    return f"""Составь {total} вопросов для самопроверки по материалу.

1. {TOPIC_RULES}
2. Виды вопросов (ровно столько каждого вида):
{plan}
3. Сложность — {level["style"]}. {level["distractors"]}.
4. Вопросы проверяют понимание, а не поиск слова. Покрой разные темы и части материала, не повторяйся.
5. У каждого вопроса: topic (из списка topics), explanation — почему верный ответ верный (2–4 предложения, своими словами,
   по материалу), hint — подсказка, которая наводит на мысль, но НЕ называет ответ, quote — дословная цитата из материала.
6. Варианты ответов — короткие, одного стиля и длины; не используй «все ответы верны» / «нет верного ответа».{avoid_text}

Верни JSON:
{{"topics": ["тема 1"],
  "questions": [{{"type": "single", "topic": "тема 1", "text": "вопрос", "options": ["а", "б", "в", "г"], "correct": 2,
                 "explanation": "почему", "hint": "подсказка", "quote": "дословная цитата"}}]}}{_part(part)}{_note(note)}

МАТЕРИАЛ:
{material}"""
